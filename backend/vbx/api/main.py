"""FastAPI application.

create_app() does what the old app.py did at import: prepare the SQLite
storage, run init_db() (all idempotent migrations), install the session
cookie, then mount every router found in vbx/api/routers/ under /api.

Adding a router: create vbx/api/routers/<domain>.py exposing `router`
(an APIRouter). Do not edit this file for that.
"""

from __future__ import annotations

import importlib
import mimetypes
import os
import pkgutil
import sys
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import Depends, FastAPI
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from starlette.middleware.sessions import SessionMiddleware

from vbx import jobs
from vbx.core import db, telegram_bot

from . import routers as routers_pkg
from .deps import csrf_protect
from .errors import ApiError, install_error_handlers
from .security import SESSION_COOKIE, SESSION_MAX_AGE, resolve_secret_key, secure_cookies

# Same registrations as the old app: Windows' registry does not know these.
mimetypes.add_type("application/manifest+json", ".webmanifest")
mimetypes.add_type("image/x-icon", ".ico")

BACKEND_DIR = Path(__file__).resolve().parents[2]
BANK_LOGO_DIR = Path(__file__).resolve().parents[1] / "static" / "banks"
DOCKER_STATIC_DIR = Path("/app/static")


def default_static_dir() -> Path:
    raw = os.environ.get("VBX_STATIC_DIR", "").strip()
    if raw:
        return Path(raw)
    if DOCKER_STATIC_DIR.is_dir():
        return DOCKER_STATIC_DIR
    return BACKEND_DIR.parent / "frontend" / "dist"


def _boot() -> None:
    """The old app.py's import-time boot steps."""
    db._prepare_sqlite_storage()
    db.init_db()
    if not jobs.jobs_enabled():
        return
    # Only a real deployment talks to Telegram at boot (the old app did this
    # unconditionally; here it is opt-in so dev servers and tests stay offline).
    conn = db.get_connection()
    try:
        cfg = telegram_bot.get_server_config(conn)
        if telegram_bot.is_configured(cfg):
            _ok, msg = telegram_bot.clear_webhook(cfg)
            print(f"Telegram: {msg}", file=sys.stderr)
    finally:
        conn.close()


@asynccontextmanager
async def _lifespan(_app: FastAPI):
    if jobs.jobs_enabled():
        jobs.start_background_jobs()
    yield


def include_routers(app: FastAPI) -> None:
    for info in sorted(pkgutil.iter_modules(routers_pkg.__path__), key=lambda i: i.name):
        if info.name.startswith("_"):
            continue
        module = importlib.import_module(f"{routers_pkg.__name__}.{info.name}")
        router = getattr(module, "router", None)
        if router is not None:
            app.include_router(router, prefix="/api")


def mount_spa(app: FastAPI, static_dir: Path) -> None:
    """Serve the built SPA, with index.html for any non-/api path that is not a file."""
    if not static_dir.is_dir():
        return
    root = static_dir.resolve()
    index = root / "index.html"

    @app.get("/{full_path:path}", include_in_schema=False)
    def spa(full_path: str):
        if full_path == "api" or full_path.startswith("api/"):
            raise ApiError(404, "Not Found")
        candidate = (root / full_path).resolve()
        if full_path and candidate.is_relative_to(root) and candidate.is_file():
            return FileResponse(candidate)
        if index.is_file():
            return FileResponse(index)
        raise ApiError(404, "Not Found")


def create_app(static_dir: str | Path | None = None) -> FastAPI:
    _boot()
    app = FastAPI(
        title="Vibe Budgeting X",
        lifespan=_lifespan,
        dependencies=[Depends(csrf_protect)],
    )
    install_error_handlers(app)
    app.add_middleware(
        SessionMiddleware,
        secret_key=resolve_secret_key(),
        session_cookie=SESSION_COOKIE,
        max_age=SESSION_MAX_AGE,
        same_site="lax",
        https_only=secure_cookies(),
    )
    include_routers(app)
    if BANK_LOGO_DIR.is_dir():
        app.mount("/static/banks", StaticFiles(directory=BANK_LOGO_DIR), name="bank-logos")
    mount_spa(app, Path(static_dir) if static_dir is not None else default_static_dir())
    return app


app = create_app()
